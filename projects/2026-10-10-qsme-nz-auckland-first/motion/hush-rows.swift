// Owner CTA rule (3 Oct 2026): no "free" on screen, anywhere. The live homepage prints a small "Free to join." line under its
// "Get started" button, and it shows in the typing shots. This finds that line in every keystroke frame and every settled
// still, so af.js can lay a soft dark patch over it (the hush). It only hides that one line; nothing is added or redrawn.
// Regenerate after any re-capture (writes af-hush.js):
//   swiftc -O hush-rows.swift -o /tmp/hush-rows && /tmp/hush-rows . > af-hush.js
import AppKit

struct Img { let w: Int; let h: Int; let p: [UInt8] }
func load(_ path: String) -> Img? {
  guard let src = CGImageSourceCreateWithURL(URL(fileURLWithPath: path) as CFURL, nil),
        let cg = CGImageSourceCreateImageAtIndex(src, 0, nil) else { return nil }
  let w = cg.width, h = cg.height
  var buf = [UInt8](repeating: 0, count: w * h * 4)
  let ctx = CGContext(data: &buf, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w * 4,
                      space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
  ctx.draw(cg, in: CGRect(x: 0, y: 0, width: w, height: h))
  return Img(w: w, h: h, p: buf)
}

/// "Free to join." in CSS px of the image, or nil when it isn't visible.
func find(_ im: Img, dpr: Double, x0: Double, x1: Double) -> [Double]? {
  let X0 = Int(x0 * dpr), X1 = min(im.w - 1, Int(x1 * dpr))
  func rgb(_ x: Int, _ y: Int) -> (Int, Int, Int) { let i = (y * im.w + x) * 4; return (Int(im.p[i]), Int(im.p[i + 1]), Int(im.p[i + 2])) }
  func isGreen(_ c: (Int, Int, Int)) -> Bool { c.1 > 130 && c.1 - c.0 > 60 && c.1 - c.2 > 40 }
  func isGrey(_ c: (Int, Int, Int)) -> Bool { let l = (c.0 * 299 + c.1 * 587 + c.2 * 114) / 1000; return l > 100 && max(c.0, c.1, c.2) - min(c.0, c.1, c.2) < 32 }
  var green = [Int](repeating: 0, count: im.h)
  for y in 0..<im.h { var n = 0; for x in X0...X1 where isGreen(rgb(x, y)) { n += 1 }; green[y] = n }
  let solid = Int(90 * dpr)                       // a button's padding rows are green edge to edge (>= 90 CSS px)
  var y = 0
  while y < im.h {
    guard green[y] >= solid else { y += 1; continue }
    // a button: solid green rows, possibly broken by its own label, 30-70 CSS px tall
    var end = y, gap = 0, yy = y + 1
    while yy < im.h && Double(gap) < 22 * dpr { if green[yy] >= solid { end = yy; gap = 0 } else { gap += 1 }; yy += 1 }
    let tall = Double(end - y) / dpr
    if tall >= 30 && tall <= 70 {
      // left edge of the button
      var bl = X1; for x in X0...X1 where isGreen(rgb(x, end - 2)) { bl = x; break }
      let tx0 = max(0, bl - Int(4 * dpr)), tx1 = min(im.w - 1, bl + Int(130 * dpr))
      var top = -1, bot = -1, misses = 0
      var ty = end + Int(6 * dpr)
      while ty < min(im.h, end + Int(70 * dpr)) {
        var n = 0; for x in tx0...tx1 where isGrey(rgb(x, ty)) { n += 1 }
        if Double(n) > 2 * dpr { if top < 0 { top = ty }; bot = ty; misses = 0 } else if top >= 0 { misses += 1; if Double(misses) > 3 * dpr { break } }
        ty += 1
      }
      if top >= 0 {
        var lx = tx1, rx = tx0
        for yy2 in top...bot { for x in tx0...tx1 where isGrey(rgb(x, yy2)) { lx = min(lx, x); rx = max(rx, x) } }
        let hh = Double(bot - top) / dpr, ww = Double(rx - lx) / dpr
        if hh >= 6 && hh <= 24 && ww >= 45 && ww <= 115 {
          return [Double(lx) / dpr, Double(top) / dpr, Double(rx) / dpr, Double(bot) / dpr].map { ($0 * 10).rounded() / 10 }
        }
      }
    }
    y = max(end, y) + 1
  }
  return nil
}

let root = CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : "."
let fm = FileManager.default
var parts: [String] = []
for k in ["dun", "chc", "ham", "akl"] {
  for m in ["d", "m"] {
    let dpr = m == "d" ? 2.0 : 4.155, xr = m == "d" ? (380.0, 640.0) : (8.0, 220.0)
    let dir = "\(root)/clips/\(k)-\(m)k"
    let files = (try? fm.contentsOfDirectory(atPath: dir).filter { $0.hasSuffix(".jpg") }.sorted()) ?? []
    let rows = files.map { f -> String in
      guard let im = load(dir + "/" + f), let r = find(im, dpr: dpr, x0: xr.0, x1: xr.1) else { return "0" }
      return "[" + r.map { String($0) }.joined(separator: ",") + "]"
    }
    parts.append("\"\(k)-\(m)k\": [" + rows.joined(separator: ",") + "]")
    // the settled still (page px; the still sits at clip_y in the layer, so add it in af.js)
    let sdpr = m == "d" ? 3.0 : 4.155
    if let im = load("\(root)/stills/\(k)-\(m).jpg"), let r = find(im, dpr: sdpr, x0: xr.0, x1: xr.1) {
      parts.append("\"\(k)-\(m)\": [" + r.map { String($0) }.joined(separator: ",") + "]")
    } else { parts.append("\"\(k)-\(m)\": 0") }
  }
}
print("// Generated by hush-rows.swift (3 Oct 2026): the homepage's \"Free to join.\" line per keystroke frame and per still (CSS px of the image; 0 = not visible).")
print("window.AF_HUSH = {" + parts.joined(separator: ", ") + "};")
