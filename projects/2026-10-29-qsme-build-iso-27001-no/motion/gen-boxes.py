#!/usr/bin/env python3
"""Turns the still grabber's box JSON (4x px) into CSS-px boxes for the kit page: motion/boxes.js."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
def css(v):
    if v is None: return None
    if isinstance(v, list) and v and isinstance(v[0], list): return [[round(x / 4, 2) for x in b] for b in v]
    if isinstance(v, list): return [round(x / 4, 2) for x in v]
    return v
full = {k: css(v) for k, v in json.load(open(f'{H}/clips/security-en-full.json'))['boxes'].items() if k != 'docHeight'}
cta = {k: css(v) for k, v in json.load(open(f'{H}/clips/seg-cta.json'))['boxes'].items() if k != 'docHeight'}
lang = {}
for f in sorted(os.listdir(f'{H}/clips/lang')):
    if f.endswith('.json'):
        lang[f[4:-5]] = {k: css(v) for k, v in json.load(open(f'{H}/clips/lang/{f}'))['boxes'].items() if k != 'docHeight'}
whip = json.load(open(f'{H}/clips/live-whip/frames.json'))['stamps']
whip916 = json.load(open(f'{H}/clips/live-whip-9x16/frames.json'))['stamps'] if os.path.exists(f'{H}/clips/live-whip-9x16/frames.json') else []
open(f'{H}/boxes.js', 'w').write('// generated by gen-boxes.py from the still grabs (CSS px of the 390-wide mobile page) and the live-whip screencast stamps\nwindow.BOX = ' + json.dumps({'full': full, 'cta': cta, 'lang': lang, 'whip': whip, 'whip916': whip916}) + ';\n')
print('boxes.js written')
